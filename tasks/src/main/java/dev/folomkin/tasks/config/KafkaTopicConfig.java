package dev.folomkin.tasks.config;

import org.apache.kafka.clients.admin.NewTopic;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.kafka.config.TopicBuilder;

@Configuration
public class KafkaTopicConfig {

    // Конфиг был добавлен на подозрение, что не создается топик.
    @Bean
    public NewTopic tasksTopic() {
        return TopicBuilder.name("tasks-topic")
                .partitions(3) // Делим на 3 части для будущего масштабирования
                .replicas(1)   // В Minikube у нас одна нода, поэтому реплика 1
                .build();
    }
}

// Отматывать назад и сомневаться в коде — это отличная практика, именно так
// формируется глубокое понимание! Давайте разберем, почему этот бин NewTopic
// был не просто «подозрением», а необходимым архитектурным шагом.
//Мы добавили этот конфиг из-за двух фундаментальных причин: одной технической
// (особенность Кафки) и одной профессиональной (касающейся промышленной
// разработки).
//------------------------------
//## Причина 1. Техническая (Особенности режима KRaft в Confluent Kafka)
//В старых версиях Кафки (которые работали с Zookeeper) брокер по умолчанию
// автоматически создавал топик, как только туда приходил первый запрос (хоть
// от отправителя, хоть от получателя).
//В современных версиях Confluent Kafka в режиме KRaft автосоздание топиков
// консьюмерами заблокировано по умолчанию из соображений безопасности. Когда
// ваши получатели (users-service и notifications-service) стартовали и
// пытались подписаться на несуществующий топик, Кафка выдавала ошибку:
//UNKNOWN_TOPIC_OR_PARTITION
//Создавая бин NewTopic, мы заставили ваш tasks-service принудительно создать
// этот топик в памяти Кафки в ту же секунду, как само Java-приложение
// включается. Когда получатели подключаются чуть позже — топик уже
// гарантированно существует, и система не падает.
//------------------------------
//## Причина 2. Профессиональная (Контроль над архитектурой данных)
//Если полагаться на «магическое» автоматическое создание топиков Кафкой,
// брокер создаст топик с дефолтными настройками (обычно это 1 партиция и 1
// реплика). Для реального продакшена это катастрофа.
//Объявляя бин NewTopic, вы берете управление в свои руки и явно задаете
// критически важные параметры:
//
//   1. .partitions(3) (Партиции / Разделы):
//   Это главный инструмент масштабирования Кафки. Одно сообщение может
//   обрабатывать только один консьюмер внутри группы. Если бы Кафка создала
//   1 партицию по умолчанию, то сколько бы подов notifications-app вы завтра
//   ни запустили в Kubernetes (хоть 10 штук), сообщения читал бы строго один
//   под, а остальные 9 просто простаивали бы. Разделив топик на 3 партиции,
//   вы заложили фундамент: теперь 3 пода смогут читать данные параллельно,
//   ускоряя обработку в 3 раза.
//   2. .replicas(1) (Реплики / Копии):
//   Это отказоустойчивость. Мы явно указали 1, потому что в Minikube у нас
//   всего один сервер Кафки. Если бы мы не управляли этим и дефолтные
//   настройки Кафки на проде потребовали бы 3 реплики, то в Minikube проект
//   бы просто не стартовал. А на реальном продакшене вы в этом месте напишете
//   .replicas(3), и Spring сам создаст топик, который скопируется на 3 сервера,
//   защищая данные от потери при падении одного из них.
//
//## Резюме:
//Этот конфиг — гарантия стабильности. Он страхует консьюмеров от ошибки
// «топик не найден» при старте и сразу создает правильную, готовую к высоким
// нагрузкам структуру данных (3 партиции) вместо слепого дефолта брокера.